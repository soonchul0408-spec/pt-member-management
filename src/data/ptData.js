export function getInitialState() {
  if (!import.meta.env.DEV) {
    return {
      members: [],
      memberships: [],
      sessions: [],
      measurements: [],
      payments: [],
      notes: [],
      workoutAssignments: [],
      workoutLogs: [],
      mealRecords: [],
      coachingNotes: [],
      communications: [],
      announcements: [],
    }
  }

  return {
    members: structuredClone(initialMembers).map((member) => ({ ...member, isSample: true })),
    memberships: structuredClone(initialMemberships),
    sessions: structuredClone(initialSessions),
    measurements: structuredClone(initialMeasurements),
    payments: structuredClone(initialPayments),
    notes: structuredClone(initialNotes),
    workoutAssignments: structuredClone(initialWorkoutAssignments),
    workoutLogs: structuredClone(initialWorkoutLogs),
    mealRecords: structuredClone(initialMealRecords),
    coachingNotes: structuredClone(initialCoachingNotes),
    communications: structuredClone(initialCommunications),
    announcements: structuredClone(initialAnnouncements),
  }
}
